"""Write docs/evidence/impact-evidence.md from the same service the /impact page uses.

Every figure is computed now from the live catalogue, the trend snapshot and the production
matching and pathway engines on synthetic personas. Nothing is typed in by hand.
Usage: python src/scripts/impact_evidence.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src" / "api"))

from app.contracts.impact import ImpactSummary  # noqa: E402
from app.features.impact import service  # noqa: E402

OUT = ROOT / "docs" / "evidence" / "impact-evidence.md"


def pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def render(d: ImpactSummary) -> str:
    agg = {a.scenario: a for a in d.aggregates}
    m, f = agg["moderate"], agg["fast"]
    fm = d.formulas
    c, fa = d.catalogue, d.fairness
    lines = [
        "# Impact evidence",
        "",
        f"**{d.persona_note}**",
        "",
        f"Trend snapshot date: {d.meta.snapshot_date.isoformat()} "
        f"(served from `{d.meta.served_from}`, fallback: {d.meta.is_fallback}). "
        "Catalogue counts are stored-record coverage; synthetic model results are estimates. "
        "Generated by `src/scripts/impact_evidence.py` "
        "using the same service as `GET /api/v1/impact/summary`; re-run to refresh.",
        "",
        f"Research observations: {d.meta.observed_from} through {d.meta.observed_to}. "
        "Historical replay is not current research.",
        "",
        "## Headline figures",
        "",
        "| Metric | Moderate | Fast | Formula |",
        "|---|---:|---:|---|",
        f"| Median free share of courses | {pct(m.median_free_course_share)} | "
        f"{pct(f.median_free_course_share)} | {fm['free_share']} |",
        f"| Median free share of hours | {pct(m.median_free_hours_share)} | "
        f"{pct(f.median_free_hours_share)} | {fm['free_hours_share']} |",
        f"| Median HRD Corp-claimable share of courses | {pct(m.median_hrd_course_share)} | "
        f"{pct(f.median_hrd_course_share)} | {fm['hrd_share']} |",
        f"| Median pathway hours | {m.median_total_hours:g} | {f.median_total_hours:g} | "
        f"{fm['hours']} |",
        f"| Median distinct SDG targets | {m.median_sdg_target_count:g} | "
        f"{f.median_sdg_target_count:g} | {fm['sdg']} |",
        f"| Median top-5 roles that change Moderate to Fast | {m.median_top5_changed:g} | "
        f"same | {fm['scenario']} |",
        "",
        "## Per persona",
        "",
        "| Persona | Scenario | Top role | Courses | Hours | Free (courses) | "
        "Free (hours) | HRD (courses) | SDG targets | Top-5 changed |",
        "|---|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for p in d.personas:
        for path in (p.moderate, p.fast):
            lines.append(
                f"| {p.persona_id} | {path.scenario} | {path.top_role_label} | "
                f"{path.course_count} | {path.total_hours:g} | "
                f"{pct(path.free_course_share)} | {pct(path.free_hours_share)} | "
                f"{pct(path.hrd_course_share)} | {path.sdg_target_count} | {p.top5_changed} |"
            )
    lines += [
        "",
        "## Catalogue coverage",
        "",
        f"Courses: {c.course_count}. Roles: {c.role_count}. Skills: {c.skill_count}. "
        f"Free courses: {c.free_course_count} ({pct(c.free_course_share)}), "
        f"free hours listed: {c.free_hours:g}; distinct linked SDG targets: {c.sdg_target_count} "
        f"across {c.role_sdg_link_count} role links. Catalogue date: {c.as_of}. "
        f"Verified on or after {c.verified_since.isoformat()} "
        f"({c.verified_window_days} days before the catalogue verification date): "
        f"{pct(c.verified_recent_share)} ({fm['verified']}).",
        "",
        "| Group | Key | Courses |",
        "|---|---|---:|",
    ]
    for label, buckets in (
        ("Language", c.by_language),
        ("Provider type", c.by_provider_type),
    ):
        lines += [f"| {label} | {b.key} | {b.count} |" for b in buckets]
    lines += [
        "",
        "## Fairness",
        "",
        f"Max rank change across {fa.variants_tested} swaps on {fa.personas_tested} personas: "
        f"**{fa.max_rank_change}**. Guardrail report passed: {fa.guardrail_report_passed} "
        f"({fa.api_inputs_checked} API inputs checked). Formula: {fm['fairness']}.",
        "",
        f"Method: {fa.method}",
        "",
        "## Why this matters",
        "",
        "Figures quoted from public pages fetched on the dates shown; stored in "
        "`src/data/seed/impact/public_evidence.json`.",
        "",
        "| Figure | Scope | What it measures | Quote | Source | Retrieved |",
        "|---|---|---|---|---|---|",
        *[
            f'| {e.figure} | {e.scope} | {e.claim} | "{e.quote}" | '
            f"[{e.publisher}]({e.url}) | {e.retrieved_at.isoformat()} |"
            for e in d.public_evidence
        ],
    ]
    lab = d.labour_context
    if lab is not None:
        lines += [
            "",
            f"Stored DOSM Labour Force Survey, month {lab.observed_month.isoformat()}: "
            f"unemployment {lab.unemployment_rate}%, participation {lab.participation_rate}% "
            f"(snapshot {lab.meta.snapshot_date.isoformat()}, retrieved "
            f"{lab.meta.sources[0].retrieved_at.isoformat()}).",
        ]
    lines += ["", "## Sources", ""]
    lines += [
        f"- {s.name} ({s.url or 'no URL'}), {s.retrieved_at.isoformat()}" for s in d.meta.sources
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT.write_text(render(service.compute_summary()), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
